-- v1.0 (etapa 3b): historial de solo adición de los cambios a los lotes de un proyecto hechos por carga masiva (CSV).
-- Aditiva: no toca datos existentes. Cada fila es un lote creado o actualizado, con lo que cambió, quién y cuándo.
create table historial_lote_proyecto (
    id bigint generated by default as identity primary key,
    proyecto_codigo varchar(80) not null,
    lote_clave varchar(20) not null,
    accion varchar(11) not null,
    origen varchar(10) not null,
    -- Qué cambió, por ejemplo «precio: 35000.00 → 36000.00; estado: DISPONIBLE → SEPARADO». En un lote nuevo, sus valores.
    cambios varchar(1000) not null,
    -- Identifica la carga (todas las filas de un mismo archivo confirmado comparten este valor).
    carga_id varchar(36) not null,
    cuenta_codigo varchar(40) not null,
    registrada_en timestamp not null,
    constraint ck_hist_lote_accion check (accion in ('CREADO', 'ACTUALIZADO')),
    constraint ck_hist_lote_origen check (origen in ('CSV'))
);
create index ix_hist_lote_proyecto on historial_lote_proyecto (proyecto_codigo, lote_clave);
