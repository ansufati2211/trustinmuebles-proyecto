-- v0.7 (F3): solicitudes de contacto del comprador y asignación del especialista a una inspección.
-- Solo agrega columnas y una tabla; no cambia datos existentes.

-- Especialista asignado por el gestor (código de cuenta). Si es nulo, cualquier especialista puede emitir el informe.
alter table evaluacion_tecnica add column especialista_asignado_codigo varchar(40);

-- Contacto: códigos de cuenta, fecha y un motivo de lista cerrada. Sin nombres, DNI, teléfonos ni texto libre (I11).
-- expediente_id es una referencia por valor (el módulo de cartera no es dueño del expediente).
-- pendiente_clave vale «comprador|caso» mientras está pendiente y es única: una sola pendiente por comprador y caso.
create table solicitud_contacto (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null,
    caso_codigo varchar(20) not null,
    comprador_codigo varchar(40) not null,
    motivo varchar(30) not null,
    estado varchar(12) not null,
    creada_en timestamp not null,
    atendida_en timestamp,
    atendida_por varchar(40),
    pendiente_clave varchar(80) unique,
    constraint ck_contacto_motivo check (motivo in ('INFORMACION_GENERAL', 'CONSULTA_DOCUMENTOS', 'CONSULTA_INSPECCION')),
    constraint ck_contacto_estado check (estado in ('PENDIENTE', 'ATENDIDA')),
    constraint ck_contacto_pendiente check ((estado = 'PENDIENTE' and pendiente_clave is not null)
        or (estado = 'ATENDIDA' and pendiente_clave is null and atendida_en is not null))
);
