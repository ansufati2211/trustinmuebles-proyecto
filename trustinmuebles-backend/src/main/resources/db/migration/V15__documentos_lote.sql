-- v0.9 (reglas v0.5): documentos del expediente de un lote y precio en otra moneda.
--
-- Un lote no tiene planos de edificación, pero sí sus propios documentos: plano perimétrico y de ubicación, memoria
-- descriptiva, certificado de zonificación y vías, y tasación. Van en su propia tabla para no mezclarlos con las cuatro
-- especialidades de una vivienda. Su estado es documental, con los mismos valores que un plano.
create table documento_lote (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null references expediente(id) on delete cascade,
    tipo varchar(30) not null,
    estado varchar(20) not null,
    observacion varchar(500),
    resumen varchar(1000),
    archivo_id varchar(36) references archivo(id),
    constraint uq_documento_lote_tipo unique (expediente_id, tipo),
    constraint ck_documento_lote_tipo check (tipo in ('PLANO_PERIMETRICO', 'MEMORIA_DESCRIPTIVA',
        'CERTIFICADO_ZONIFICACION', 'TASACION')),
    constraint ck_documento_lote_estado check (estado in ('PRESENTADO', 'OBSERVADO', 'NO_PRESENTADO', 'NO_APLICA'))
);

-- El precio base de una subasta de la SBN se publica en dólares. Los casos existentes siguen en soles.
alter table caso_lote add column moneda varchar(3) default 'PEN' not null;
alter table caso_lote add constraint ck_caso_moneda check (moneda in ('PEN', 'USD'));
-- Nota propia del precio (por ejemplo, «precio base de la subasta»). Si no hay, se usa la nota general.
alter table caso_lote add column precio_nota varchar(200);
-- Enlace a la publicación oficial de la que salen los datos del caso.
alter table caso_lote add column fuente_url varchar(300);
