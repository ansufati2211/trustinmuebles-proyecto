-- v0.8 (B5, decisión 2): decisiones de captación del gestor. Historial de solo adición: la aplicación solo inserta filas
-- (no hay ruta para editarlas ni borrarlas). Solo códigos de cuenta, fecha, una decisión y un motivo de lista cerrada, sin
-- texto libre (I11). El caso se guarda por valor, como en solicitud_contacto: el módulo de cartera no es dueño del
-- expediente. No interviene en los indicadores A ni B ni bloquea la publicación (I15).
create table decision_captacion (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null,
    caso_codigo varchar(20) not null,
    decision varchar(30) not null,
    motivo varchar(40) not null,
    cuenta_codigo varchar(40) not null,
    registrada_en timestamp not null,
    constraint ck_decision_captacion check (decision in ('CAPTAR', 'CAPTAR_CON_CONDICIONES', 'NO_CAPTAR_POR_AHORA')),
    constraint ck_decision_motivo check (motivo in ('DOCUMENTACION_COMPLETA', 'REGULARIZACION_EN_CURSO', 'CARGA_VIGENTE',
        'PROCESO_JUDICIAL', 'INFORMACION_INSUFICIENTE', 'OTRO_MOTIVO_COMERCIAL'))
);
create index ix_decision_captacion_caso on decision_captacion (caso_codigo, id);
