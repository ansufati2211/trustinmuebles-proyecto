-- v1.0 (etapa 3a): proyectos de urbanización, sus hitos y sus lotes. Aditiva: no borra datos.
--
-- Un proyecto agrupa los lotes de una habilitación urbana. Su código es el nombre en minúsculas, sin tildes y con
-- guiones («Campiña del Olivar» → «campina-del-olivar»), el mismo que calcula Proyecto.codigoDe en Java.
create table proyecto (
    id bigint generated by default as identity primary key,
    codigo varchar(80) not null,
    nombre varchar(120) not null,
    distrito varchar(80),
    descripcion varchar(1500),
    -- Enlace al recorrido o video del proyecto publicado por la inmobiliaria; opcional.
    recorrido_url varchar(300),
    -- Código del caso de la partida matriz del proyecto; opcional. Su indicador A se muestra en los lotes sin caso propio.
    caso_matriz_codigo varchar(40),
    creado_en timestamp default current_timestamp not null,
    constraint uq_proyecto_codigo unique (codigo)
);

-- Hitos del proyecto: informativos, no intervienen en el indicador A.
create table hito_proyecto (
    id bigint generated by default as identity primary key,
    proyecto_id bigint not null references proyecto(id) on delete cascade,
    orden int not null,
    nombre varchar(160) not null,
    estado varchar(11) not null,
    fecha date,
    constraint ck_hito_estado check (estado in ('COMPLETADO', 'EN_PROCESO', 'PENDIENTE'))
);
create index ix_hito_proyecto on hito_proyecto (proyecto_id);

-- Lote del plano del proyecto. Si tiene caso propio (caso_codigo), el estado comercial vigente es el del caso y el lote
-- aparece en el catálogo como ese caso; si no, su indicador A es el de la partida matriz del proyecto.
create table lote_proyecto (
    id bigint generated by default as identity primary key,
    proyecto_id bigint not null references proyecto(id) on delete cascade,
    manzana varchar(4) not null,
    numero int not null,
    area_m2 decimal(10, 2) not null,
    precio decimal(12, 2),
    moneda varchar(3) default 'PEN' not null,
    estado_comercial varchar(10) default 'DISPONIBLE' not null,
    independizacion varchar(17) default 'EN_PARTIDA_MATRIZ' not null,
    zonificacion varchar(20),
    caso_codigo varchar(40),
    publicado boolean default false not null,
    creado_en timestamp default current_timestamp not null,
    constraint uq_lote_proyecto unique (proyecto_id, manzana, numero),
    constraint uq_lote_proyecto_caso unique (caso_codigo),
    constraint ck_lote_area check (area_m2 > 0),
    constraint ck_lote_precio check (precio is null or precio > 0),
    constraint ck_lote_numero check (numero > 0),
    constraint ck_lote_moneda check (moneda in ('PEN', 'USD')),
    constraint ck_lote_estado_comercial check (estado_comercial in ('DISPONIBLE', 'SEPARADO', 'VENDIDO')),
    constraint ck_lote_independizacion
        check (independizacion in ('PARTIDA_PROPIA', 'EN_PARTIDA_MATRIZ', 'NO_CONSTA'))
);
create index ix_lote_proyecto on lote_proyecto (proyecto_id);

-- El caso se vincula a su proyecto por código. El texto «proyecto» (V18) se conserva como nombre visible.
alter table caso_lote add column proyecto_codigo varchar(80);
alter table caso_lote add constraint fk_caso_proyecto foreign key (proyecto_codigo) references proyecto (codigo);
create index ix_caso_lote_proyecto_codigo on caso_lote (proyecto_codigo);

-- Fecha de alta del caso, para ordenar por novedad junto con los lotes de proyecto. Los existentes reciben la fecha de
-- esta migración y se desempatan por su orden de carga.
alter table caso_lote add column creado_en timestamp default current_timestamp not null;

-- Migración del texto a la referencia, sin perder datos: un proyecto por cada nombre distinto que ya tenían los casos
-- (con el distrito de sus casos) y el código en cada caso. El texto queda igual.
insert into proyecto (codigo, nombre, distrito)
select slug, min(proyecto), min(distrito) from (
    select trim(both '-' from regexp_replace(
               replace(replace(replace(replace(replace(replace(replace(lower(trim(proyecto)),
                   'á', 'a'), 'é', 'e'), 'í', 'i'), 'ó', 'o'), 'ú', 'u'), 'ñ', 'n'), 'ü', 'u'),
               '[^a-z0-9]+', '-', 'g')) as slug,
           proyecto, distrito
    from caso_lote where proyecto is not null and trim(proyecto) <> ''
) t
where slug <> ''
group by slug;

update caso_lote set proyecto_codigo = (select p.codigo from proyecto p where p.codigo = trim(both '-' from
        regexp_replace(replace(replace(replace(replace(replace(replace(replace(lower(trim(caso_lote.proyecto)),
            'á', 'a'), 'é', 'e'), 'í', 'i'), 'ó', 'o'), 'ú', 'u'), 'ñ', 'n'), 'ü', 'u'),
        '[^a-z0-9]+', '-', 'g')))
where proyecto is not null and trim(proyecto) <> '';
