-- v1.0 (etapa 1): rol ASESOR (permisos de revisor y de gestor), titularidad comercial del caso e historial de
-- autorizaciones. Aditiva: no borra datos. Los casos existentes quedan como PARTICULAR.

alter table usuario drop constraint ck_usuario_rol;
alter table usuario add constraint ck_usuario_rol
    check (rol in ('COMPRADOR', 'REVISOR', 'ESPECIALISTA', 'GESTOR', 'PROPIETARIO', 'ASESOR'));

-- INMOBILIARIA: inmueble que la inmobiliaria comercializa por cuenta propia (la autorización la registra el asesor o
-- el gestor en su nombre). PARTICULAR: inmueble de un propietario, que es el único que autoriza.
alter table caso_lote add column titularidad_comercial varchar(14) not null default 'PARTICULAR';
alter table caso_lote add constraint ck_caso_titularidad_comercial
    check (titularidad_comercial in ('INMOBILIARIA', 'PARTICULAR'));

-- Historial de solo adición de las autorizaciones: quién la otorgó o retiró, en nombre de quién y cuándo.
create table historial_autorizacion (
    id bigint generated by default as identity primary key,
    caso_codigo varchar(40) not null,
    accion varchar(10) not null,
    en_nombre_de varchar(14) not null,
    cuenta_codigo varchar(40) not null,
    registrada_en timestamp not null,
    constraint ck_hist_autorizacion_accion check (accion in ('OTORGADA', 'RETIRADA')),
    constraint ck_hist_autorizacion_nombre check (en_nombre_de in ('INMOBILIARIA', 'PARTICULAR'))
);
create index ix_hist_autorizacion_caso on historial_autorizacion (caso_codigo);

-- Precarga en una base existente: el lote de Santiago pasa a ser de la inmobiliaria, con su autorización registrada
-- por asesor-01. En una base nueva la tabla está vacía y lo hace la carga de contenido (CasosSeeder).
update caso_lote set titularidad_comercial = 'INMOBILIARIA' where codigo in ('11081204', 'SIM-11081204');
insert into historial_autorizacion (caso_codigo, accion, en_nombre_de, cuenta_codigo, registrada_en)
    select replace(codigo, 'SIM-', ''), 'OTORGADA', 'INMOBILIARIA', 'asesor-01', autorizacion_fecha from caso_lote
    where titularidad_comercial = 'INMOBILIARIA' and autorizacion_fecha is not null;
