-- Esquema compatible con PostgreSQL y H2 (modo PostgreSQL)

create table usuario (
    id bigint generated by default as identity primary key,
    nombre varchar(255) not null,
    email varchar(255) not null unique,
    password_hash varchar(255) not null,
    rol varchar(30) not null,
    creado_en timestamp not null
);

create table archivo (
    id varchar(36) primary key,
    nombre_original varchar(255) not null,
    content_type varchar(100) not null,
    tamano bigint not null,
    sha256 varchar(64) not null,
    publico boolean not null,
    creado_en timestamp not null
);

create table inmueble (
    id bigint generated by default as identity primary key,
    titulo varchar(255) not null,
    ubicacion varchar(255) not null,
    direccion varchar(255) not null,
    descripcion varchar(2000),
    precio_usd numeric(14,2) not null,
    habitaciones integer not null,
    banos integer not null,
    area_m2 numeric(10,2) not null,
    numero_partida varchar(30) not null,
    vendedor_nombre varchar(255) not null,
    imagen_url varchar(500),
    publicado_en timestamp not null
);

create table plano2d (
    id bigint generated by default as identity primary key,
    inmueble_id bigint not null references inmueble(id),
    nombre varchar(255) not null,
    imagen_url varchar(500) not null
);

create table tour3d (
    id bigint generated by default as identity primary key,
    inmueble_id bigint not null unique references inmueble(id),
    titulo varchar(255) not null,
    url varchar(500) not null
);

create table evaluacion_legal (
    id bigint generated by default as identity primary key,
    inmueble_id bigint not null,
    nivel varchar(10) not null,
    nivel_dominio varchar(10) not null,
    nivel_gravamenes varchar(10) not null,
    nivel_procesos varchar(10) not null,
    hash_copia varchar(64) not null,
    fecha timestamp not null
);
create index ix_evaluacion_inmueble on evaluacion_legal(inmueble_id);

create table hallazgo_legal (
    id bigint generated by default as identity primary key,
    evaluacion_id bigint not null references evaluacion_legal(id),
    categoria varchar(30) not null,
    nivel varchar(10) not null,
    codigo varchar(50) not null,
    titulo varchar(255) not null,
    explicacion varchar(1000),
    recomendacion varchar(1000),
    texto_registral varchar(1000)
);

create table inspeccion (
    id bigint generated by default as identity primary key,
    inmueble_id bigint not null,
    plano_id bigint not null,
    inspector_nombre varchar(255) not null,
    dictamen varchar(2000),
    estado varchar(10) not null,
    nivel_estructural varchar(10),
    fecha timestamp not null
);
create index ix_inspeccion_inmueble on inspeccion(inmueble_id);

create table pin_falla (
    id bigint generated by default as identity primary key,
    inspeccion_id bigint not null references inspeccion(id),
    x double precision not null,
    y double precision not null,
    severidad varchar(10) not null,
    titulo varchar(255) not null,
    descripcion varchar(1000)
);

create table transaccion (
    id bigint generated by default as identity primary key,
    inmueble_id bigint not null,
    comprador_id bigint not null,
    gestor_id bigint,
    etapa varchar(30) not null,
    precio_acordado numeric(14,2) not null,
    creada_en timestamp not null,
    actualizada_en timestamp not null
);
create index ix_transaccion_comprador on transaccion(comprador_id);

create table evento_timeline (
    id bigint generated by default as identity primary key,
    transaccion_id bigint not null references transaccion(id),
    tipo varchar(40) not null,
    descripcion varchar(500) not null,
    fecha timestamp not null,
    hash_previo varchar(64) not null,
    hash varchar(64) not null
);

create table documento (
    id bigint generated by default as identity primary key,
    transaccion_id bigint not null references transaccion(id),
    nombre varchar(255) not null,
    tipo varchar(40) not null,
    archivo_id varchar(36) not null,
    estado_firma varchar(20) not null,
    sha256 varchar(64) not null,
    subido_en timestamp not null,
    firmado_en timestamp,
    firmado_por_id bigint
);

create table mensaje_asesor (
    id bigint generated by default as identity primary key,
    transaccion_id bigint not null references transaccion(id),
    autor_id bigint not null,
    texto varchar(2000) not null,
    fecha timestamp not null
);

create table propiedad_adquirida (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null,
    inmueble_id bigint not null,
    transaccion_id bigint not null unique,
    fecha_compra timestamp not null,
    valor_compra numeric(14,2) not null
);

create table mantenimiento (
    id bigint generated by default as identity primary key,
    propiedad_id bigint not null references propiedad_adquirida(id),
    fecha date not null,
    servicio varchar(255) not null,
    inversion_usd numeric(14,2) not null,
    comprobante_archivo_id varchar(36)
);

create table ticket_garantia (
    id bigint generated by default as identity primary key,
    propiedad_id bigint not null references propiedad_adquirida(id),
    transaccion_id bigint not null,
    plano_id bigint not null,
    pin_x double precision,
    pin_y double precision,
    titulo varchar(255) not null,
    descripcion varchar(2000),
    proveedor varchar(255),
    estado varchar(30) not null,
    prioridad varchar(10) not null,
    creado_en timestamp not null,
    actualizado_en timestamp not null
);
