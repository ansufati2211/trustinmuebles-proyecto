-- v0.7 (F2): historial de evaluaciones del indicador A, de solo adición (I12). Cada recálculo agrega una fila con el
-- color anterior y el nuevo, los motivos, los faltantes, la versión de reglas, el origen y la cuenta que actuó.
-- No guarda nombres, DNI ni teléfonos: solo el código de la cuenta (I11).
-- expediente_id es una referencia por valor, sin clave foránea: el historial se conserva aunque se borre una
-- partida transcrita, y el módulo de clasificación no depende del de expedientes.

create table historial_evaluacion (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null,
    registrada_en timestamp not null,
    estado_anterior varchar(10),
    estado_nuevo varchar(10) not null,
    motivos varchar(10000) not null,
    faltantes varchar(4000) not null,
    version_reglas varchar(30) not null,
    origen varchar(20) not null,
    cuenta_codigo varchar(40) not null,
    constraint ck_historial_anterior check (estado_anterior is null
        or estado_anterior in ('VERDE', 'AMARILLO', 'ROJO', 'GRIS')),
    constraint ck_historial_nuevo check (estado_nuevo in ('VERDE', 'AMARILLO', 'ROJO', 'GRIS')),
    constraint ck_historial_origen check (origen in ('EDICION', 'PLANO_ADJUNTO', 'PARTIDA_TRANSCRITA', 'CARGA_INICIAL'))
);

create index ix_historial_expediente on historial_evaluacion (expediente_id);
