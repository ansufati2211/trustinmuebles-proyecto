-- Esquema lógico del MVP (Tabla 14 y Figura 6 del informe APF1).
-- Todos los datos son sintéticos (RN-01). Las claves de respuesta del estudio NO viven aquí.

create table usuario (
    id bigint generated by default as identity primary key,
    codigo_cuenta varchar(40) not null unique,
    password_hash varchar(100) not null,
    rol varchar(20) not null,
    creado_en timestamp not null,
    constraint ck_usuario_rol check (rol in ('COMPRADOR', 'REVISOR'))
);

-- Documentos PDF sintéticos, cifrados en disco por el módulo de almacenamiento.
create table archivo (
    id varchar(36) primary key,
    nombre_original varchar(255) not null,
    content_type varchar(100) not null,
    tamano bigint not null,
    sha256 varchar(64) not null,
    publico boolean not null,
    creado_en timestamp not null
);

create table caso_lote (
    id bigint generated by default as identity primary key,
    codigo varchar(20) not null unique,
    contexto varchar(255) not null,
    sintetico boolean not null default true,
    responsable_id bigint not null references usuario(id),
    constraint ck_caso_sintetico check (sintetico = true)
);

create table expediente (
    id bigint generated by default as identity primary key,
    caso_id bigint not null unique references caso_lote(id),
    version bigint not null default 0,
    condicion_representada varchar(255) not null,
    titularidad varchar(255) not null,
    completitud varchar(20) not null,
    fecha_referencial date not null,
    nota varchar(500),
    documento_archivo_id varchar(36) references archivo(id),
    actualizado_en timestamp not null,
    constraint ck_expediente_completitud check (completitud in ('COMPLETA', 'INCOMPLETA', 'DESCONOCIDA'))
);

create table anotacion (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null references expediente(id) on delete cascade,
    referencia varchar(20) not null,
    estado varchar(20) not null,
    descripcion varchar(255),
    orden integer not null,
    constraint uq_anotacion unique (expediente_id, referencia),
    constraint ck_anotacion_estado check (estado in ('VIGENTE', 'CANCELADA', 'DESCONOCIDO'))
);

create table regla (
    id bigint generated by default as identity primary key,
    codigo varchar(40) not null,
    version varchar(30) not null,
    prioridad varchar(20) not null,
    tipo_condicion varchar(40) not null,
    prefijo_referencia varchar(20),
    titulo varchar(160) not null,
    explicacion varchar(500) not null,
    estado_revision varchar(120) not null,
    constraint uq_regla unique (codigo, version),
    constraint ck_regla_prioridad check (prioridad in ('PRIORITARIA', 'REVISION'))
);

create table condicion_contemplada (
    id bigint generated by default as identity primary key,
    version_reglas varchar(30) not null,
    texto varchar(255) not null,
    constraint uq_condicion unique (version_reglas, texto)
);

-- Una evaluación vigente como máximo por expediente; sin historial (Anexo 13).
-- expediente_id es una referencia por valor: el módulo de clasificación no depende del de expedientes.
create table evaluacion (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null unique references expediente(id) on delete cascade,
    estado varchar(10) not null,
    detalle varchar(10000) not null,
    version_reglas varchar(30) not null,
    expediente_version bigint not null,
    calculada_en timestamp not null,
    constraint ck_evaluacion_estado check (estado in ('VERDE', 'AMARILLO', 'ROJO', 'GRIS'))
);

create table evaluacion_regla (
    evaluacion_id bigint not null references evaluacion(id) on delete cascade,
    regla_id bigint not null references regla(id),
    primary key (evaluacion_id, regla_id)
);

create table item_checklist (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null references expediente(id) on delete cascade,
    nombre varchar(120) not null,
    estado varchar(20) not null,
    observacion varchar(255),
    orden integer not null,
    constraint ck_item_estado check (estado in ('PENDIENTE', 'REVISADO', 'OBSERVADO'))
);

create table termino_glosario (
    id bigint generated by default as identity primary key,
    concepto varchar(80) not null unique,
    explicacion varchar(500) not null,
    version varchar(30) not null,
    estado_revision varchar(120) not null
);

create table expediente_termino (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null references expediente(id) on delete cascade,
    termino_id bigint not null references termino_glosario(id),
    constraint uq_expediente_termino unique (expediente_id, termino_id)
);
