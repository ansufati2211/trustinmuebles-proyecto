-- v1.0 (etapa 4): interesados (CRM del asesor), sus notas y sus citas. Solo agrega tablas; no cambia datos existentes.
-- Ningún dato de estas tablas interviene en el motor de reglas ni cambia el indicador A.
-- Nunca se guarda un DNI: el contacto es un nombre de pila y un celular o un correo, con consentimiento y su versión.

create table interes (
    id bigint generated by default as identity primary key,
    creado_en timestamp not null,
    actualizado_en timestamp not null,
    -- A qué se refiere: un caso publicado, un lote de proyecto, un proyecto o una búsqueda general. Por valor.
    origen varchar(10) not null,
    caso_codigo varchar(40),
    proyecto_codigo varchar(80),
    lote_clave varchar(12),
    referencia varchar(140),
    inmueble varchar(250),
    -- Lo que busca.
    zona varchar(80),
    tipo varchar(10),
    presupuesto_min decimal(14, 2),
    presupuesto_max decimal(14, 2),
    moneda varchar(3),
    area_deseada decimal(12, 2),
    forma_pago varchar(12) not null,
    mensaje varchar(300),
    -- Contacto: nombre de pila y un solo medio. Nunca DNI.
    nombre varchar(40) not null,
    medio varchar(8) not null,
    contacto varchar(120) not null,
    consentimiento boolean not null,
    consentimiento_version varchar(20) not null,
    consentimiento_en timestamp not null,
    -- Seguimiento comercial.
    etapa varchar(20) not null,
    responsable varchar(40),
    proxima_accion varchar(160),
    proxima_accion_fecha date,
    -- Precarga: días respecto del arranque para la próxima acción; null en un registro real o ya tocado por una persona.
    semilla_desfase int,
    constraint ck_interes_origen check (origen in ('CASO', 'LOTE', 'PROYECTO', 'GENERAL')),
    constraint ck_interes_tipo check (tipo is null or tipo in ('LOTE', 'VIVIENDA')),
    constraint ck_interes_moneda check (moneda is null or moneda in ('PEN', 'USD')),
    constraint ck_interes_pago check (forma_pago in ('CONTADO', 'FINANCIADO', 'POR_DEFINIR')),
    constraint ck_interes_medio check (medio in ('CELULAR', 'CORREO')),
    constraint ck_interes_consentimiento check (consentimiento = true),
    constraint ck_interes_etapa check (etapa in ('NUEVO', 'CONTACTADO', 'CITA_AGENDADA', 'VISITA_REALIZADA',
        'SEPARACION', 'VENTA', 'DESCARTADO')),
    constraint ck_interes_presupuesto check (presupuesto_min is null or presupuesto_max is null
        or presupuesto_min <= presupuesto_max)
);
create index ix_interes_etapa on interes (etapa);
create index ix_interes_proyecto on interes (proyecto_codigo);

-- Notas de seguimiento: solo se agregan (la aplicación no las edita ni las borra). Se van con su interesado si este
-- pide que se elimine su registro.
create table nota_interes (
    id bigint generated by default as identity primary key,
    interes_id bigint not null references interes (id) on delete cascade,
    texto varchar(1000) not null,
    cuenta_codigo varchar(40) not null,
    creada_en timestamp not null
);
create index ix_nota_interes on nota_interes (interes_id);

-- Cita o consulta: hasta dos fechas propuestas con franja; el asesor confirma una, la reprograma o la rechaza con motivo.
create table cita (
    id bigint generated by default as identity primary key,
    interes_id bigint not null references interes (id) on delete cascade,
    modalidad varchar(20) not null,
    fecha1 date not null,
    franja1 varchar(6) not null,
    fecha2 date,
    franja2 varchar(6),
    estado varchar(12) not null,
    fecha_acordada date,
    franja_acordada varchar(6),
    motivo_rechazo varchar(300),
    creada_en timestamp not null,
    actualizada_en timestamp not null,
    atendida_por varchar(40),
    semilla_desfase int,
    constraint ck_cita_modalidad check (modalidad in ('VISITA_AL_LOTE', 'REUNION_EN_OFICINA', 'LLAMADA')),
    constraint ck_cita_franja check (franja1 in ('MANANA', 'TARDE') and (franja2 is null or franja2 in ('MANANA', 'TARDE'))
        and (franja_acordada is null or franja_acordada in ('MANANA', 'TARDE'))),
    constraint ck_cita_estado check (estado in ('SOLICITADA', 'CONFIRMADA', 'REPROGRAMADA', 'RECHAZADA')),
    constraint ck_cita_acordada check ((estado in ('CONFIRMADA', 'REPROGRAMADA') and fecha_acordada is not null
        and franja_acordada is not null) or (estado = 'RECHAZADA' and motivo_rechazo is not null)
        or estado = 'SOLICITADA')
);
create index ix_cita_interes on cita (interes_id);

-- La precarga de interesados se aplica una sola vez: si luego se eliminan a pedido, no vuelven a crearse.
create table interes_semilla (
    version varchar(10) primary key,
    aplicada_en timestamp not null
);
