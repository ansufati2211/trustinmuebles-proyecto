-- v2.0 (tanda 2): asesor asignado, citas con tipo y dos fechas, seguimiento por etapas y separación del lote
-- (RF32, RF35, RF36, RF41, RF42, RN28 a RN31). Aditiva: no cambia datos existentes ni migraciones anteriores.

-- RF36: dos etapas nuevas del seguimiento (Revisado y Acuerdo). Se reemplaza la restricción de valores de V21 por una
-- que acepta las nueve etapas; los valores ya guardados siguen siendo válidos.
alter table interes drop constraint ck_interes_etapa;
alter table interes add constraint ck_interes_etapa check (etapa in ('NUEVO', 'CONTACTADO', 'REVISADO', 'CITA_AGENDADA',
    'VISITA_REALIZADA', 'ACUERDO', 'SEPARACION', 'VENTA', 'DESCARTADO'));

-- RN31: cuántas separaciones del interesado se liberaron o descartaron (control del tope).
alter table interes add column descartes int default 0 not null;

-- RF35: asesor a cargo de la cita (cuenta de asesor o de gestor). Null en las citas pedidas desde el portal hasta que
-- un asesor las atiende. El tipo es la columna modalidad (visita al lote, reunión en oficina o llamada) y las dos fechas
-- son fecha1 (principal) y fecha2 (opcional, la alternativa pedida por el cliente), que ya existían.
alter table cita add column asesor varchar(40);

-- RF36: cada cambio de etapa, con quién lo hizo y cuándo.
create table historial_etapa_interes (
    id bigint generated by default as identity primary key,
    interes_id bigint not null references interes (id) on delete cascade,
    desde varchar(20) not null,
    hacia varchar(20) not null,
    cuenta_codigo varchar(40) not null,
    registrado_en timestamp not null,
    motivo varchar(300)
);
create index ix_historial_etapa_interes on historial_etapa_interes (interes_id);

-- RF41, RF42, RN29, RN31: separación o venta de un lote (o de un caso) por un interesado. ACTIVA mientras el lote está
-- separado; VENDIDA al cerrarse la venta (con o sin depósito); LIBERADA cuando se descarta, con fecha y motivo.
create table separacion_lote (
    id bigint generated by default as identity primary key,
    interes_id bigint not null references interes (id) on delete cascade,
    caso_codigo varchar(40),
    proyecto_codigo varchar(80),
    lote_clave varchar(20),
    estado varchar(10) not null,
    con_deposito boolean default false not null,
    creada_en timestamp not null,
    creada_por varchar(40) not null,
    cerrada_en timestamp,
    cerrada_por varchar(40),
    motivo varchar(300),
    constraint ck_separacion_estado check (estado in ('ACTIVA', 'VENDIDA', 'LIBERADA')),
    constraint ck_separacion_liberada check (estado <> 'LIBERADA' or (motivo is not null and cerrada_en is not null))
);
create index ix_separacion_interes on separacion_lote (interes_id);
create index ix_separacion_lote on separacion_lote (proyecto_codigo, lote_clave);
create index ix_separacion_caso on separacion_lote (caso_codigo);
