-- Expediente técnico de planos (4 especialidades) y evaluación técnica por un especialista.
-- Los planos y el informe son datos del expediente; el informe no cambia el color de la pre-evaluación documental.

alter table usuario drop constraint ck_usuario_rol;
alter table usuario add constraint ck_usuario_rol check (rol in ('COMPRADOR', 'REVISOR', 'ESPECIALISTA'));

alter table expediente add column tipo_predio varchar(10) not null default 'LOTE';
alter table expediente add column area_construida_inscrita numeric(10,2);
alter table expediente add constraint ck_expediente_tipo_predio check (tipo_predio in ('LOTE', 'VIVIENDA'));

create table plano_tecnico (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null references expediente(id) on delete cascade,
    especialidad varchar(20) not null,
    estado varchar(20) not null,
    area_construida numeric(10,2),
    sistema_constructivo varchar(30),
    observacion varchar(500),
    archivo_id varchar(36) references archivo(id),
    constraint uq_plano_especialidad unique (expediente_id, especialidad),
    constraint ck_plano_especialidad check (especialidad in ('ARQUITECTURA', 'ESTRUCTURAS', 'ELECTRICAS', 'SANITARIAS')),
    constraint ck_plano_estado check (estado in ('PRESENTADO', 'OBSERVADO', 'NO_PRESENTADO', 'NO_APLICA'))
);

-- expediente_id es una referencia por valor: el módulo de inspección no depende del de expedientes.
create table evaluacion_tecnica (
    id bigint generated by default as identity primary key,
    expediente_id bigint not null unique references expediente(id) on delete cascade,
    estado varchar(20) not null,
    resultado varchar(20),
    profesional varchar(120),
    colegiatura varchar(40),
    fecha_solicitud date,
    fecha_inspeccion date,
    verif_arquitectura varchar(15),
    verif_estructuras varchar(15),
    verif_electricas varchar(15),
    verif_sanitarias varchar(15),
    observaciones varchar(1500),
    conclusiones varchar(1500),
    estudios_adicionales varchar(1000),
    actualizado_en timestamp not null,
    constraint ck_evtec_estado check (estado in ('SOLICITADA', 'EN_INSPECCION', 'EMITIDO')),
    constraint ck_evtec_resultado check (resultado is null or resultado in ('FAVORABLE', 'CON_OBSERVACIONES', 'CON_RIESGO'))
);
