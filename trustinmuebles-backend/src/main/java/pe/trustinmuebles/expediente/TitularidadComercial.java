package pe.trustinmuebles.expediente;

/**
 * v1.0: quién comercializa el inmueble. INMOBILIARIA: la inmobiliaria por cuenta propia (por ejemplo, un lote de sus
 * proyectos de urbanización); su autorización la registra el asesor o el gestor en nombre de la inmobiliaria.
 * PARTICULAR: un propietario que encarga la venta; solo él autoriza. En ambos casos publicar exige autorización vigente.
 */
public enum TitularidadComercial {
    INMOBILIARIA, PARTICULAR
}
